import { test, expect, type Page } from '@playwright/test'
async function freeze(page: Page) { await page.clock.setFixedTime(new Date('2026-10-16T16:00:00Z')) }
async function ready(page: Page) { await expect(page.locator('h1')).toBeVisible(); await expect(page.getByText('Opening local workspace…')).not.toBeVisible() }
async function snapshot(page: Page, name: string) {
  return page.evaluate(async dbName => {
    const database = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open(dbName); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    const tx = database.transaction([...database.objectStoreNames], 'readonly')
    const result: Record<string, unknown[]> = {}
    await Promise.all([...database.objectStoreNames].map(table => new Promise<void>((resolve, reject) => {
      const request = tx.objectStore(table).getAll(); request.onsuccess = () => { result[table] = request.result; resolve() }; request.onerror = () => reject(request.error)
    })))
    database.close(); return result
  }, name)
}
test('demo uses real forms, split receipts, persistence, reset, offline reload and a separate workspace', async ({ page, context }) => {
  await freeze(page)
  await page.goto('/#/plan'); await ready(page)
  await page.getByRole('button', { name: '+ Add obligation' }).click()
  const bill = page.getByRole('dialog', { name: 'Add obligation' })
  await bill.getByLabel('Obligation name').fill('Personal isolation sentinel')
  await bill.getByLabel('Planned amount (USD)').fill('12.34')
  await bill.getByRole('button', { name: 'Save obligation' }).click(); await expect(bill).not.toBeVisible()
  const normal = await snapshot(page, 'accrynt-local-v1')
  await page.getByRole('link', { name: 'Try demo', exact: true }).click()
  await expect(page.getByText('DEMO · SYNTHETIC DATA', { exact: true })).toBeVisible()
  for (const route of ['/', '/plan', '/ledger', '/debts', '/reports', '/settings']) {
    await page.goto(`/?demo=1#${route}`); await ready(page)
    await expect(page.locator('.error-panel')).not.toBeVisible()
  }
  await page.goto('/?demo=1#/debts'); await ready(page)
  const card = page.locator('.debt-card').filter({ has: page.getByRole('heading', { name: 'Fictional revolving card', exact: true }) })
  await card.getByRole('button', { name: 'Record payment', exact: true }).click()
  const payment = page.getByRole('dialog', { name: 'Record payment' })
  await payment.getByLabel('Description', { exact: true }).fill('Synthetic browser payment')
  await payment.getByLabel('Payment amount (USD)').fill('40.00')
  await payment.getByLabel('Interest included in payment (USD)').fill('10.00')
  await payment.getByLabel('Related obligation').selectOption({ label: 'Fictional card payment · 2026-10' })
  await expect(payment.getByLabel('Description', { exact: true })).toHaveValue('Synthetic browser payment')
  await expect(payment.getByLabel('Payment amount (USD)')).toHaveValue('40.00')
  await expect(payment.getByLabel('Interest included in payment (USD)')).toHaveValue('10.00')
  await payment.getByLabel('Interest is already included').check()
  await expect(payment.getByLabel('Payment amount (USD)')).toHaveValue('40.00')
  await payment.getByRole('button', { name: 'Confirm payment' }).click(); await expect(payment).not.toBeVisible()
  await expect(card.locator('.debt-balance')).toHaveText('$2,124.37')
  await page.reload(); await ready(page)
  await expect(card.locator('.debt-balance')).toHaveText('$2,124.37')
  await page.goto('/?demo=1#/ledger'); await ready(page)
  const row = page.getByRole('row').filter({ hasText: 'Synthetic browser payment' })
  await row.getByText('Payment split', { exact: true }).click()
  await expect(row).toContainText('Principal $30.00'); await expect(row).toContainText('Interest $10.00')
  page.once('dialog', d => d.accept())
  await row.getByRole('button', { name: 'Undo payment' }).click(); await expect(row).not.toBeVisible()
  await page.goto('/?demo=1#/settings'); await ready(page)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JSON backup' }).click()
  expect((await download).suggestedFilename()).toContain('DEMO-SYNTHETIC')
  await page.getByLabel('Theme', { exact: true }).selectOption('dark')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await page.reload(); await ready(page)
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
  await context.setOffline(true); await page.reload(); await ready(page)
  await expect(page.locator('.app-root')).toHaveAttribute('data-theme', 'dark')
  await context.setOffline(false)
  page.once('dialog', d => d.accept()); await page.getByRole('button', { name: 'Reset demo', exact: true }).click()
  await expect.poll(async () => (await snapshot(page, 'accrynt-demo-v1')).debts.length).toBe(6)
  await page.getByRole('link', { name: 'Return to my workspace' }).click(); await ready(page)
  expect(await snapshot(page, 'accrynt-local-v1')).toEqual(normal)
})
test('simultaneous demo entry seeds once and skip links preserve hash routes', async ({ page, context }) => {
  await freeze(page)
  const second = await context.newPage(); await freeze(second)
  await Promise.all([page.goto('/?demo=1#/plan'), second.goto('/?demo=1#/ledger')])
  await Promise.all([ready(page), ready(second)])
  const data = await snapshot(page, 'accrynt-demo-v1')
  expect(data.months.length).toBe(6); expect(data.debts.length).toBe(6); expect(data.obligations.length).toBe(59)
  await page.keyboard.press('Tab'); await expect(page.getByRole('link', { name: 'Skip to content', exact: true })).toBeFocused()
  await page.keyboard.press('Enter'); await expect(page.locator('#main-content')).toBeFocused(); await expect(page).toHaveURL(/#\/plan$/)
  await page.getByRole('link', { name: 'Skip to navigation', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(page.locator('#main-navigation')).toBeFocused(); await expect(page).toHaveURL(/#\/plan$/)
  await page.setViewportSize({ width: 320, height: 800 })
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Menu', exact: true }).click(); await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Menu', exact: true })).toBeFocused()
  await expect(page.getByRole('navigation')).not.toBeVisible()
})
