async function restore(page: Page, content: unknown) {
  await page.goto('/#/settings')
  await page.getByLabel('Select an Accrynt backup file').setInputFiles({ name: 'synthetic-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(content)) })
  await expect(page.getByText('Validated backup:', { exact: false })).toBeVisible()
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Replace local records with backup' }).click()
  await expect(page.getByText('Validated backup:', { exact: false })).not.toBeVisible()
}
async function backup(page: Page) {
  await page.goto('/#/settings')
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JSON backup' }).click()
  const stream = await (await pending).createReadStream()
  if (!stream) throw new Error('No backup stream')
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  return JSON.parse(Buffer.concat(chunks).toString('utf8'))
}
async function fixedDate(page: Page) { await page.clock.install({ time: new Date('2026-10-16T12:00:00Z') }) }
async function pay(page: Page, amount: string, interest: string) {
  const dialog = page.getByRole('dialog', { name: 'Record payment', exact: true })
  await dialog.getByLabel('Payment amount (USD)').fill(amount)
  await dialog.getByLabel('Interest included in payment (USD)').fill(interest)
  await dialog.getByRole('button', { name: 'Confirm payment' }).click()
  await expect(dialog).not.toBeVisible()
}
const metric = (page: Page, label: string) => page.locator('.metric-card').filter({ has: page.locator('.metric-label').filter({ hasText: label }) })

test('one payment updates principal, partial bill status, cashflow, and Ledger; undo and backup stay consistent', async ({ page }) => {
  await fixedDate(page); await restore(page, legacy)
  await page.goto('/#/')
  await expect(metric(page, 'Tracked available')).toContainText('—')
  await page.getByRole('button', { name: 'Set opening balance' }).click()
  await page.getByLabel('Opening balance (USD)').fill('1000')
  await page.getByRole('button', { name: 'Save opening balance' }).click()
  await page.goto('/#/ledger'); await page.getByRole('button', { name: '+ Record transaction' }).click()
  const transaction = page.getByRole('dialog', { name: 'Transaction', exact: true })
  await transaction.getByLabel('Description').fill('Synthetic received income')
  await transaction.getByRole('combobox', { name: 'Type', exact: true }).selectOption('income')
  await transaction.getByLabel('Amount (USD)', { exact: true }).fill('500')
  await transaction.getByRole('button', { name: 'Save transaction' }).click()
  await page.goto('/#/plan')
  let row = page.getByRole('row').filter({ hasText: 'Synthetic card bill' })
  await row.getByRole('button', { name: 'Record payment' }).click()
  await pay(page, '100', '10')
  await expect(row).toContainText('Partial'); await expect(row).toContainText('$50.00 remaining')
  await page.goto('/#/debts'); await expect(page.locator('.debt-balance')).toHaveText('$910.00')
  await page.goto('/#/'); await expect(metric(page, 'Tracked available')).toContainText('$1,400.00')
  await expect(metric(page, 'After outstanding bills')).toContainText('$1,350.00')
  await expect(metric(page, 'Still committed')).toContainText('$50.00')
  await page.getByRole('button', { name: 'Record payment', exact: true }).click()
  await pay(page, '50', '5')
  await page.goto('/#/plan'); row = page.getByRole('row').filter({ hasText: 'Synthetic card bill' })
  await expect(row.getByText('Paid', { exact: true })).toBeVisible()
  await expect(row.getByRole('checkbox')).toBeDisabled()
  await page.goto('/#/debts'); await expect(page.locator('.debt-balance')).toHaveText('$865.00')
  await page.goto('/#/ledger')
  const second = page.getByRole('row').filter({ hasText: /\$50\.00/ })
  await second.getByText('Payment split', { exact: true }).click()
  await expect(second).toContainText('Principal $45.00')
  page.once('dialog', d => d.accept())
  await second.getByRole('button', { name: 'Undo payment' }).click()
  await expect(second).not.toBeVisible()
  await page.goto('/#/plan'); await expect(row).toContainText('Partial')
  const exported = await backup(page)
  expect(exported.schemaVersion).toBe(3)
  expect(exported.debts[0].balanceCents).toBe(91000)
  expect(exported.months[0].openingCents).toBe(100000)
  expect(exported.transactions).toHaveLength(2)
  expect(exported.transactions.find((t: { payment: unknown }) => t.payment).payment).toMatchObject({ principalCents: 9000, interestCents: 1000 })
  await restore(page, exported)
  await page.goto('/#/'); await expect(metric(page, 'After outstanding bills')).toContainText('$1,350.00')
  await page.reload(); await expect(metric(page, 'Tracked available')).toContainText('$1,400.00')
})

test('recurring bills and expected income carry forward once, preserve monthly edits, and survive full backup replacement', async ({ page }) => {
  await fixedDate(page); await page.goto('/#/plan')
  await page.getByText('Recurring bills & income · 0 active', { exact: true }).click()
  async function add(name: string, kind: 'bill' | 'income', amount: string) {
    await page.getByRole('button', { name: '+ Add recurring item' }).click()
    const dialog = page.getByRole('dialog', { name: 'Recurring item', exact: true })
    await dialog.getByLabel('Name', { exact: true }).fill(name)
    await dialog.getByLabel('Recurring type').selectOption(kind)
    await dialog.getByLabel('Recurring amount (USD)').fill(amount)
    await dialog.getByLabel(kind === 'bill' ? 'Due day (optional)' : 'Expected day (optional)').fill('31')
    await dialog.getByRole('button', { name: 'Save recurring item' }).click()
    await expect(dialog).not.toBeVisible()
  }
  await add('Synthetic recurring utility', 'bill', '100')
  await expect(page.getByRole('row').filter({ hasText: 'Synthetic recurring utility' })).toBeVisible()
  await add('Synthetic recurring income', 'income', '500')
  await expect(metric(page, 'Expected income')).toContainText('$500.00')
  const october = page.getByRole('row').filter({ hasText: 'Synthetic recurring utility' })
  await october.getByRole('button', { name: 'Edit', exact: true }).click()
  const billDialog = page.getByRole('dialog', { name: 'Edit obligation' })
  await billDialog.getByLabel('Planned amount (USD)').fill('123')
  await billDialog.getByRole('button', { name: 'Save obligation' }).click()
  const rule = page.locator('.recurring-panel .scheduled-row').filter({ hasText: 'Synthetic recurring utility' })
  await rule.getByRole('button', { name: 'Edit recurring item' }).click()
  const recurring = page.getByRole('dialog', { name: 'Recurring item', exact: true })
  await recurring.getByLabel('Recurring amount (USD)').fill('200')
  await recurring.getByRole('button', { name: 'Save recurring item' }).click()
  await expect(october).toContainText('$123.00')
  await page.getByRole('button', { name: 'Next month' }).click()
  const november = page.getByRole('row').filter({ hasText: 'Synthetic recurring utility' })
  await expect(november).toContainText('$200.00'); await expect(november).toContainText('2026-11-30')
  await page.reload() // Selected month starts at current month on launch.
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(november).toHaveCount(1)
  page.once('dialog', d => d.accept()); await november.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(november).not.toBeVisible()
  const scheduled = page.locator('.expected-income-panel .scheduled-row')
  await scheduled.getByRole('button', { name: 'Edit this month', exact: true }).click()
  const incomeDialog = page.getByRole('dialog', { name: 'Edit expected income' })
  await incomeDialog.getByLabel('Recurring amount (USD)').fill('600')
  await incomeDialog.getByRole('button', { name: 'Save recurring item' }).click()
  await expect(metric(page, 'Expected income')).toContainText('$600.00')
  await scheduled.getByRole('button', { name: 'Record receipt' }).click()
  const transaction = page.getByRole('dialog', { name: 'Transaction', exact: true })
  await expect(transaction.getByLabel('Amount (USD)', { exact: true })).toHaveValue('600.00')
  await transaction.getByLabel('Amount (USD)', { exact: true }).fill('200')
  await transaction.getByRole('button', { name: 'Save transaction' }).click()
  await scheduled.getByRole('button', { name: 'Skip this month', exact: true }).click()
  await expect(metric(page, 'Expected income')).toContainText('$0.00')
  await scheduled.getByRole('button', { name: 'Restore this month' }).click()
  await expect(metric(page, 'Expected income')).toContainText('$600.00')
  await page.getByText('Recurring bills & income · 2 active', { exact: true }).click()
  await rule.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Synthetic recurring utility' })).not.toBeVisible()
  await expect(metric(page, 'Expected income')).toContainText('$500.00')
  const exported = await backup(page)
  expect(exported.recurringRules).toHaveLength(2)
  expect(exported.transactions).toHaveLength(1)
  expect(exported.transactions[0]).toMatchObject({ kind: 'income', amountCents: 20000, date: '2026-10-16' })
  expect(exported.recurringOccurrences.find((o: { month: string; kind: string }) => o.month === '2026-11' && o.kind === 'bill').cancelled).toBe(true)
  const clear = async (d: import('@playwright/test').Dialog) => { if (d.type() === 'prompt') await d.accept('DELETE'); else await d.accept() }
  page.on('dialog', clear); await page.getByRole('button', { name: 'Delete all local records' }).click(); page.off('dialog', clear)
  await expect(page.getByRole('button', { name: 'Load optional October example' })).toBeVisible()
  await restore(page, exported)
  const restored = await backup(page)
  expect(restored.recurringRules).toEqual(exported.recurringRules)
  expect(restored.recurringOccurrences).toEqual(exported.recurringOccurrences)
  expect(restored.transactions).toEqual(exported.transactions)
})

