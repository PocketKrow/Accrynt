test('a stale payment form in another tab cannot reduce debt twice', async ({ page, context }) => {
  await fixedDate(page); await restore(page, legacy)
  const other = await context.newPage(); await fixedDate(other)
  for (const tab of [page, other]) {
    await tab.goto('/#/debts'); await tab.locator('.debt-card').getByRole('button', { name: 'Record payment', exact: true }).click()
  }
  await pay(page, '100', '10')
  const stale = other.getByRole('dialog', { name: 'Record payment', exact: true })
  await stale.getByRole('button', { name: 'Confirm payment' }).click()
  await expect(stale.getByRole('alert')).toContainText('changed while you were editing')
  await stale.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(other.locator('.debt-balance')).toHaveText('$910.00')
  expect((await backup(page)).transactions).toHaveLength(1)
  await other.close()
})

