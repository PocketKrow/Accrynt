import { test, expect } from '@playwright/test'
import { downloadBackup } from './support/backup'

test('first-use opening cash, bill, planned income, receipt, payment, cash review and external backup agree', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-16T16:00:00Z'))
  await page.goto('/#/')
  await page.getByRole('region', { name: 'Get started', exact: true }).getByRole('button', { name: 'Set opening cash', exact: true }).click()
  await page.getByLabel('Opening balance (USD)').fill('250')
  await page.getByRole('button', { name: 'Save opening balance', exact: true }).click()
  await expect(page.locator('.inline-editor')).not.toBeVisible()
  await page.getByRole('link', { name: /Monthly Plan/ }).click()
  await page.getByRole('button', { name: '+ Add obligation', exact: true }).click()
  const bill = page.getByRole('dialog', { name: 'Add obligation', exact: true })
  await bill.getByLabel('Obligation name').fill('Synthetic first utility')
  await bill.getByLabel('Planned amount (USD)').fill('50')
  await bill.getByRole('button', { name: 'Save obligation', exact: true }).click()
  await expect(bill).not.toBeVisible()
  await page.getByText('Recurring bills & income · 0 active', { exact: true }).click()
  await page.getByRole('button', { name: '+ Add recurring item', exact: true }).click()
  const rule = page.getByRole('dialog', { name: 'Recurring item', exact: true })
  await rule.getByLabel('Name', { exact: true }).fill('Synthetic first payroll')
  await rule.getByLabel('Recurring type').selectOption('income')
  await rule.getByLabel('Recurring amount (USD)').fill('500')
  await rule.getByRole('button', { name: 'Save recurring item', exact: true }).click()
  await expect(rule).not.toBeVisible()
  const metric = (label: string) => page.locator('.metric-card').filter({ has: page.locator('.metric-label').getByText(label, { exact: true }) })
  await expect(metric('Expected income')).toContainText('$500.00')
  await page.getByRole('link', { name: /Overview/ }).click()
  await expect(metric('Tracked available')).toContainText('$250.00') // plan is not a deposit
  await page.getByRole('link', { name: /Monthly Plan/ }).click()
  await page.locator('.expected-income-panel .scheduled-row').getByRole('button', { name: 'Record receipt', exact: true }).click()
  const receipt = page.getByRole('dialog', { name: 'Transaction', exact: true })
  await receipt.getByLabel('Amount (USD)', { exact: true }).fill('200')
  await receipt.getByRole('button', { name: 'Save transaction', exact: true }).click()
  await expect(receipt).not.toBeVisible()
  await expect(metric('Expected income')).toContainText('$500.00')
  await page.getByRole('row').filter({ hasText: 'Synthetic first utility' }).getByRole('button', { name: 'Record payment Synthetic first utility', exact: true }).click()
  const payment = page.getByRole('dialog', { name: 'Record payment', exact: true })
  await payment.getByLabel('Payment amount (USD)').fill('25')
  await payment.getByRole('button', { name: 'Confirm payment', exact: true }).click()
  await expect(payment).not.toBeVisible()
  await page.getByRole('link', { name: /Overview/ }).click()
  await expect(metric('Tracked available')).toContainText('$425.00')
  await expect(metric('After outstanding bills')).toContainText('$400.00')
  await page.getByRole('button', { name: 'View breakdown: After outstanding bills', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Synthetic first utility')
  await page.getByRole('button', { name: 'Close cash breakdown', exact: true }).click()
  const backup = JSON.parse((await downloadBackup(page)).buffer.toString('utf8'))
  expect(backup.months[0].openingCents).toBe(25000)
  expect(backup.transactions).toHaveLength(2)
  expect(backup.transactions.find((row: { kind: string }) => row.kind === 'income').incomeOccurrenceId).toBe(backup.recurringOccurrences[0].id)
  expect(backup.transactions.find((row: { payment: unknown }) => row.payment).obligationId).toBe(backup.obligations[0].id)
})
